def get_route_coords(route_name: str) -> tuple[float, float] | None:
    """
    根据路线名称查找坐标。
    先精确匹配，再前缀匹配。
    """
    if not route_name:
        return None

    # 精确匹配
    if route_name in ROUTE_COORDINATES:
        return ROUTE_COORDINATES[route_name]

    # 前缀匹配
    for name, coords in ROUTE_COORDINATES.items():
        if route_name.startswith(name) or name.startswith(route_name):
            return coords

    return None
